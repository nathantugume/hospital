        const isEdit = !!sample;
        const overlay = document.createElement('div');
        overlay.className = 'modal-overlay';
        overlay.innerHTML = `
            <div class="modal-container">
                <div class="modal-header">
                    <h2 class="modal-title">${isEdit ? 'Edit Sample Collection' : 'Add Sample Collection'}</h2>
                    <button class="modal-close" aria-label="Close">&times;</button>
                </div>
                <div class="modal-body">
                    <p class="text-sm text-gray-500 mb-4">${isEdit ? 'Update sample collection details' : 'Enter sample collection details'}</p>
                    <div class="space-y-4">
                        <div class="grid-2">
                            <div class="form-group">
                                <label class="form-label">Patient Name *</label>
                                <div id="patientSelect" class="radix-select"></div>
                            </div>
                            <div class="form-group">
                                <label class="form-label">Test Name *</label>
                                <div id="testSelect" class="radix-select"></div>
                            </div>
                        </div>
                        <div class="grid-2">
                            <div class="form-group">
                                <label class="form-label">Sample Type *</label>
                                <div id="sampleTypeSelect" class="radix-select"></div>
                            </div>
                            <div class="form-group">
                                <label class="form-label">Collection Date *</label>
                                <input type="date" id="collectionDate" value="${isEdit ? sample.collectionDate : new Date().toISOString().split('T')[0]}" class="form-input">
                            </div>
                        </div>
                        <div class="grid-2">
                            <div class="form-group">
                                <label class="form-label">Collected By *</label>
                                <div id="collectorSelect" class="radix-select"></div>
                            </div>
                            <div class="form-group">
                                <label class="form-label">Status *</label>
                                <div id="statusSelect" class="radix-select"></div>
                            </div>
                        </div>
                    </div>
                </div>
                <div class="modal-footer">
                    <button type="button" class="cancel-modal inline-flex items-center justify-center rounded-md border border-gray-300 bg-white hover:bg-gray-50 h-10 px-4 py-2 text-sm font-medium">Cancel</button>
                    <button type="button" id="saveSampleBtn" class="inline-flex items-center justify-center rounded-md bg-primary text-white hover:bg-primary/90 h-10 px-4 py-2 text-sm font-medium">${isEdit ? 'Update Sample' : 'Add Sample'}</button>
                </div>
            </div>
        `;
        document.body.appendChild(overlay);
        activeModal = overlay;

        // Initialize selects
        const patientSelect = new RadixSelect('patientSelect', patients.map(p => ({ value: p, label: p })), isEdit ? sample.patientName : null);
        const testSelect = new RadixSelect('testSelect', tests.map(t => ({ value: t, label: t })), isEdit ? sample.testName : null);
        const sampleTypeSelect = new RadixSelect('sampleTypeSelect', sampleTypes.map(s => ({ value: s, label: s })), isEdit ? sample.sampleType : null);
        const collectorSelect = new RadixSelect('collectorSelect', collectors.map(c => ({ value: c, label: c })), isEdit ? sample.collectedBy : null);
        const statusSelect = new RadixSelect('statusSelect', statuses.map(s => ({ value: s, label: s })), isEdit ? sample.status : null);

        // Close handlers
        overlay.querySelector('.modal-close')?.addEventListener('click', () => closeModal());
        overlay.querySelector('.cancel-modal')?.addEventListener('click', () => closeModal());
        overlay.addEventListener('click', (e) => { if (e.target === overlay) closeModal(); });

        // Save handler
        overlay.querySelector('#saveSampleBtn')?.addEventListener('click', () => {
            const patientName = patientSelect.getValue();
            const testName = testSelect.getValue();
            const sampleType = sampleTypeSelect.getValue();
            const collectionDate = overlay.querySelector('#collectionDate').value;
            const collectedBy = collectorSelect.getValue();
            const status = statusSelect.getValue();

            if (!patientName) { showToast('Please select a patient', true); return; }
            if (!testName) { showToast('Please select a test', true); return; }
            if (!sampleType) { showToast('Please select a sample type', true); return; }
            if (!collectionDate) { showToast('Please select a collection date', true); return; }
            if (!collectedBy) { showToast('Please select a collector', true); return; }
            if (!status) { showToast('Please select a status', true); return; }

            if (isEdit) {
                const index = samples.findIndex(s => s.id === sample.id);
                if (index !== -1) {
                    samples[index] = { ...samples[index], patientName, testName, sampleType, collectionDate, collectedBy, status };
                    showToast('Sample updated successfully');
                }
            } else {
                const newId = `SMP-${String(samples.length + 1).padStart(3, '0')}`;
                samples.push({ id: newId, patientName, testName, sampleType, collectionDate, collectedBy, status });
                showToast('Sample added successfully');
            }
            renderTable();
            closeModal();
        });
    }

    // ========== Radix Select Class ==========
    class RadixSelect {
        constructor(containerId, options, initialValue) {
            this.container = document.getElementById(containerId);
            this.options = options;
            this.value = initialValue;
            this.render();
        }
        render() {
            const selected = this.options.find(o => o.value === this.value);
            this.container.innerHTML = `<button type="button" class="radix-select-trigger"><span class="flex-1 text-left">${selected ? selected.label : 'Select option'}</span><svg class="h-4 w-4 opacity-50" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><polyline points="6 9 12 15 18 9"></polyline></svg></button>`;
            this.trigger = this.container.querySelector('.radix-select-trigger');
            this.trigger.addEventListener('click', (e) => { e.stopPropagation(); this.toggle(); });
        }
        toggle() { this.isOpen ? this.close() : this.open(); }
        open() {
            if (this.menu) this.menu.remove();
            const rect = this.trigger.getBoundingClientRect();
            this.menu = document.createElement('div');
            this.menu.className = 'radix-select-content';
            this.menu.style.position = 'fixed';
            this.menu.style.zIndex = '1100';
            this.menu.style.width = `${rect.width}px`;
            this.menu.style.minWidth = `${rect.width}px`;
            this.menu.style.maxWidth = `${rect.width}px`;
            this.menu.innerHTML = this.options.map(opt => `<div class="radix-select-item" data-value="${opt.value}">${opt.label}</div>`).join('');
            document.body.appendChild(this.menu);
            this.menu.style.top = `${rect.bottom + 4}px`;
            this.menu.style.left = `${rect.left}px`;
            this.isOpen = true;
            if (this.trigger) this.trigger.querySelector('svg').style.transform = 'rotate(180deg)';
            this.menu.querySelectorAll('.radix-select-item').forEach(item => {
                item.addEventListener('click', () => { this.setValue(item.dataset.value, item.textContent); this.close(); });
            });
            const closeHandler = (e) => { if (!this.menu.contains(e.target) && e.target !== this.trigger) this.close(); };
            setTimeout(() => document.addEventListener('click', closeHandler), 10);
            this.closeHandler = closeHandler;
        }
        setValue(value, label) { this.value = value; if (this.trigger) this.trigger.querySelector('.flex-1').textContent = label; this.close(); }
        close() { if (this.menu) { this.menu.remove(); this.menu = null; } this.isOpen = false; if (this.trigger) this.trigger.querySelector('svg').style.transform = ''; if (this.closeHandler) document.removeEventListener('click', this.closeHandler); }
        getValue() { return this.value; }
    }

    // ========== Filter & Render ==========
    function getFilteredSamples() {
        let filtered = [...samples];
        if (currentTab === "collected") filtered = filtered.filter(s => s.status === "Collected");
        else if (currentTab === "pending") filtered = filtered.filter(s => s.status === "Pending");
        else if (currentTab === "rejected") filtered = filtered.filter(s => s.status === "Rejected");
        if (searchQuery) {
            const q = searchQuery.toLowerCase();
            filtered = filtered.filter(s => s.patientName.toLowerCase().includes(q) || s.id.toLowerCase().includes(q) || s.testName.toLowerCase().includes(q));
        }
        if (typeFilter !== "all") filtered = filtered.filter(s => s.sampleType === typeFilter);
        return filtered;
    }

    function statusBadgeClass(status) {
        if (status === "Collected") return "status-collected";
        if (status === "Pending") return "status-pending";
        if (status === "Rejected") return "status-rejected";
        return "bg-gray-100 text-gray-800";
    }

    function renderTable() {
        const filtered = getFilteredSamples();
        const tbody = document.getElementById('samplesTableBody');
        
        if (filtered.length === 0) {
            tbody.innerHTML = `<tr><td colspan="8" class="text-center py-8 text-gray-500">No samples found</td></tr>`;
        } else {
            tbody.innerHTML = filtered.map(sample => `
                <tr class="border-b transition-colors hover:bg-gray-50">
                    <td class="p-4 align-middle font-medium">${sample.id}</td>
                    <td class="p-4 align-middle"><div class="font-medium">${sample.patientName}</div></td>
                    <td class="p-4 align-middle">${sample.testName}</td>
                    <td class="p-4 align-middle">${sample.sampleType}</td>
                    <td class="p-4 align-middle">${sample.collectionDate}</td>
                    <td class="p-4 align-middle">${sample.collectedBy}</td>
                    <td class="p-4 align-middle"><span class="inline-flex rounded-full px-2 py-0.5 text-xs font-semibold ${statusBadgeClass(sample.status)}">${sample.status}</span></td>
                    <td class="p-4 align-middle text-center">
                        <button class="action-menu-btn inline-flex items-center justify-center rounded-md hover:bg-gray-100 h-8 w-8" data-id="${sample.id}">
                            <svg class="h-4 w-4 text-gray-600" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="1"></circle><circle cx="19" cy="12" r="1"></circle><circle cx="5" cy="12" r="1"></circle></svg>
                        </button>
                    </td>
                </tr>
            `).join('');
        }
        
        document.querySelectorAll('.action-menu-btn').forEach(btn => {
            btn.addEventListener('click', (e) => {
                e.stopPropagation();
                const sample = samples.find(s => s.id === btn.dataset.id);
                if (sample) showActionMenu(btn, sample);
            });
        });
    }

    // ========== Tabs ==========
    function activateTab(tabId) {
        document.querySelectorAll('.tab-trigger').forEach(btn => {
            const isActive = btn.dataset.tab === tabId;
            btn.setAttribute('data-state', isActive ? 'active' : 'inactive');
            if (isActive) {
                btn.classList.add('bg-white', 'text-gray-900', 'shadow-sm');
                btn.classList.remove('text-gray-500', 'bg-transparent');
            } else {
                btn.classList.remove('bg-white', 'text-gray-900', 'shadow-sm');
                btn.classList.add('text-gray-500', 'bg-transparent');
            }
        });
        currentTab = tabId;
        renderTable();
    }

    // ========== Filter Dropdown ==========
    const filterBtn = document.getElementById('filterBtn');
    const filterDropdown = document.getElementById('filterDropdown');

    filterBtn?.addEventListener('click', (e) => {
        e.stopPropagation();
        const rect = filterBtn.getBoundingClientRect();
        filterDropdown.style.top = `${rect.bottom + 4}px`;
        filterDropdown.style.left = `${rect.left}px`;
        filterDropdown.classList.toggle('hidden');
    });

    filterDropdown?.querySelectorAll('.dropdown-item').forEach(item => {
        item.addEventListener('click', () => {
            typeFilter = item.dataset.filter;
            filterDropdown.classList.add('hidden');
            renderTable();
        });
    });

    document.addEventListener('click', (e) => {
        if (!filterBtn?.contains(e.target) && !filterDropdown?.contains(e.target)) {
            filterDropdown?.classList.add('hidden');
        }
    });

    // ========== Event Listeners ==========
    document.getElementById('searchInput')?.addEventListener('input', (e) => { searchQuery = e.target.value.toLowerCase(); renderTable(); });
    document.getElementById('addSampleBtn')?.addEventListener('click', () => showSampleModal());
    document.getElementById('exportBtn')?.addEventListener('click', () => {
        const data = getFilteredSamples();
        const headers = ["Sample ID", "Patient Name", "Test Name", "Sample Type", "Collection Date", "Collected By", "Status"];
        const rows = data.map(s => [s.id, s.patientName, s.testName, s.sampleType, s.collectionDate, s.collectedBy, s.status]);
        const csv = [headers, ...rows].map(row => row.join(",")).join("\n");
        const blob = new Blob([csv], {type: "text/csv"});
        const a = document.createElement('a');
        a.href = URL.createObjectURL(blob);
        a.download = `sample_collection_${new Date().toISOString().slice(0,10)}.csv`;
        a.click();
        URL.revokeObjectURL(a.href);
        showToast("Export complete");
    });

    document.querySelectorAll('.tab-trigger').forEach(trigger => {
        trigger.addEventListener('click', () => activateTab(trigger.dataset.tab));
    });

    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape') {
            closeModal();
            closeActionMenu();
            filterDropdown?.classList.add('hidden');
        }
    });

    // ========== Initialize ==========
    activateTab('all');
</script>

