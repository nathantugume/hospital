function openGoogleMaps() {
    // Find the address by looking for the location icon's parent container
    const locationIcon = document.querySelector('svg path[d*="M20 10c0 4.993"]');
    
    if (locationIcon) {
        // Navigate up to find the <p> tag containing the address
        const addressContainer = locationIcon.closest('.flex.items-start.gap-2');
        const addressElement = addressContainer ? addressContainer.querySelector('p') : null;
        
        if (addressElement) {
            const address = addressElement.textContent.trim();
            const encodedAddress = encodeURIComponent(address);
            window.open(`https://www.google.com/maps/dir/?api=1&destination=${encodedAddress}`, '_blank');
        } else {
            alert('Address not found');
        }
    } else {
        // Fallback: Try to find by the Location heading
        const locationHeadings = document.querySelectorAll('h3');
        let addressFound = false;
        
        locationHeadings.forEach(heading => {
            if (heading.textContent.trim() === 'Location' && !addressFound) {
                const addressElement = heading.nextElementSibling?.querySelector('p');
                if (addressElement) {
                    const address = addressElement.textContent.trim();
                    const encodedAddress = encodeURIComponent(address);
                    window.open(`https://www.google.com/maps/dir/?api=1&destination=${encodedAddress}`, '_blank');
                    addressFound = true;
                }
            }
        });
        
if (!addressFound) {
    alert('Address not found');
}
    }
}

