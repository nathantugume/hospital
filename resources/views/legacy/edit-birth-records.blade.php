    // ============ UNSAVED CHANGES TRACKING ============
    let formChanged = false;
    const form = document.getElementById('birthRecordForm');
    
    form.querySelectorAll('input, textarea').forEach(el => {
        el.addEventListener('change', () => { formChanged = true; });
        el.addEventListener('input', () => { formChanged = true; });
    });

    window.addEventListener('beforeunload', (e) => {
        if (formChanged) {
            e.preventDefault();
            e.returnValue = 'You have unsaved changes. Are you sure you want to leave?';
            return '';
        }
    });

    // ============ FORM VALIDATION & SUBMISSION ============
    form.addEventListener('submit', (e) => {
        e.preventDefault();
        
        // Reset error states
        form.querySelectorAll('input, textarea').forEach(el => el.classList.remove('input-error'));
        
        // Required fields
        const requiredFields = [
            { id: 'childFirstName', name: 'Child First Name' },
            { id: 'childLastName', name: 'Child Last Name' },
            { id: 'motherFirstName', name: 'Mother First Name' },
            { id: 'motherLastName', name: 'Mother Last Name' },
            { id: 'placeOfBirth', name: 'Place of Birth' },
            { id: 'weight', name: 'Weight' }
        ];
        
        let isValid = true;
        let firstError = null;
        
        // Check required fields
        requiredFields.forEach(field => {
            const input = document.getElementById(field.id);
            if (!input) return;
            const value = input.value.trim();
            if (!value) {
                isValid = false;
                input.classList.add('input-error');
                if (!firstError) firstError = input;
            }
        });
        
        // Validate weight
        const weight = parseFloat(document.getElementById('weight').value);
        if (isNaN(weight) || weight < 0.5 || weight > 10) {
            isValid = false;
            document.getElementById('weight').classList.add('input-error');
            if (!firstError) firstError = document.getElementById('weight');
            showToast('⚠️ Weight must be between 0.5 and 10 kg', 'warning');
            return;
        }
        
        // Validate length if provided
        const length = document.getElementById('length').value;
        if (length && (parseFloat(length) < 20 || parseFloat(length) > 70)) {
            isValid = false;
            document.getElementById('length').classList.add('input-error');
            if (!firstError) firstError = document.getElementById('length');
            showToast('⚠️ Length must be between 20 and 70 cm', 'warning');
            return;
        }
        
        if (!isValid) {
            showToast('⚠️ Please fill in all required fields', 'error');
            if (firstError) firstError.focus();
            return;
        }
        
        // Show loading state
        const saveBtn = document.getElementById('saveBtn');
        const saveText = saveBtn.querySelector('.save-text');
        const saveIcon = saveBtn.querySelector('.save-icon');
        const loadingIcon = saveBtn.querySelector('.loading-icon');
        
        saveText.textContent = 'Saving...';
        saveIcon.classList.add('hidden');
        loadingIcon.classList.remove('hidden');
        saveBtn.disabled = true;
        
        // Simulate save
        setTimeout(() => {
            formChanged = false;
            saveText.textContent = 'Save Changes';
            saveIcon.classList.remove('hidden');
            loadingIcon.classList.add('hidden');
            saveBtn.disabled = false;
            showToast('✅ Birth record updated successfully!', 'success');
        }, 1200);
    });

