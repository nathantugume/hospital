            const hasAppointments = dayAppointments.length;
            const isSelected = dateStr === currentDate;
            const isWeekend = (new Date(year, month, day).getDay() === 0 || new Date(year, month, day).getDay() === 6);
            html += `<div class="h-16 p-1 border rounded-md relative ${isSelected ? 'bg-indigo-50 border-indigo-500' : ''} ${isWeekend ? 'bg-red-50/30' : ''} cursor-pointer calendar-day" data-date="${dateStr}"><div class="text-right text-sm">${day}</div>${hasAppointments > 0 ? `<div class="absolute bottom-1 left-0 right-0 flex justify-center gap-0.5">${Array(hasAppointments > 3 ? 3 : hasAppointments).fill('<div class="h-1.5 w-1.5 rounded-full bg-primary"></div>').join('')}${hasAppointments > 3 ? '<div class="text-[10px] text-gray-400">+</div>' : ''}</div>` : ''}</div>`;
        }
        html += `</div><div class="mt-4 flex items-center gap-4"><div class="flex items-center gap-1"><div class="h-3 w-3 rounded-full bg-primary"></div><span class="text-sm">Appointments</span></div><div class="flex items-center gap-1"><div class="h-3 w-3 rounded-full bg-red-200"></div><span class="text-sm">Time Off</span></div></div></div>`;
        document.getElementById('calendarTab').innerHTML = html;
        
        document.querySelectorAll('.calendar-day').forEach(el => {
            el.addEventListener('click', () => {
                currentDate = el.dataset.date;
                document.getElementById('selectedDate').value = currentDate;
                renderCurrentTab();
                renderCalendarView();
            });
        });
    }

    function renderCurrentTab() {
        if (currentTab === 'list') renderListView();
        else if (currentTab === 'day') renderDayView();
        else if (currentTab === 'calendar') renderCalendarView();
    }

    // Tab switching
    function initTabs() {
        document.querySelectorAll('.schedule-tab').forEach(tab => {
            tab.addEventListener('click', () => {
                currentTab = tab.dataset.tab;
                document.querySelectorAll('.schedule-tab').forEach(t => {
                    t.classList.remove('bg-white', 'text-indigo-700', 'shadow-sm');
                    t.classList.add('text-gray-600');
                });
                tab.classList.add('bg-white', 'text-indigo-700', 'shadow-sm');
                document.querySelectorAll('.tab-content').forEach(content => content.classList.remove('active'));
                document.getElementById(`${currentTab}Tab`).classList.add('active');
                renderCurrentTab();
            });
        });
    }

    // Modal Logic
    const modal = document.getElementById('addSlotModal'), backdrop = document.getElementById('modalBackdrop');
    function openModal() { modal.classList.remove('hidden'); backdrop.classList.remove('hidden'); document.body.style.overflow = 'hidden'; }
    function closeModal() { modal.classList.add('hidden'); backdrop.classList.add('hidden'); document.body.style.overflow = ''; }
    document.getElementById('addSlotBtn')?.addEventListener('click', openModal);
    document.getElementById('cancelModalBtn')?.addEventListener('click', closeModal);
    document.getElementById('closeModalBtn')?.addEventListener('click', closeModal);
    backdrop?.addEventListener('click', closeModal);
    document.getElementById('confirmAddSlotBtn')?.addEventListener('click', () => {
        showToast(`Slot added successfully`);
        closeModal();
    });

    // Dropdowns
    function setupDropdown(triggerId, dropdownId, optionsClass, onSelect) {
        const trigger = document.getElementById(triggerId), dropdown = document.getElementById(dropdownId);
        trigger?.addEventListener('click', (e) => { e.stopPropagation(); dropdown.classList.toggle('hidden'); });
        document.querySelectorAll(`.${optionsClass}`).forEach(opt => opt.addEventListener('click', () => { onSelect(opt); dropdown.classList.add('hidden'); }));
        document.addEventListener('click', (e) => { if (!trigger?.contains(e.target) && !dropdown?.contains(e.target)) dropdown?.classList.add('hidden'); });
    }
    setupDropdown('timeSelectTrigger', 'timeSelectDropdown', 'time-option', (opt) => { document.getElementById('selectedTimeText').innerText = opt.dataset.time; });
    setupDropdown('durationSelectTrigger', 'durationSelectDropdown', 'duration-option', (opt) => { document.getElementById('selectedDurationText').innerText = opt.dataset.duration + ' minutes'; });
    setupDropdown('repeatSelectTrigger', 'repeatSelectDropdown', 'repeat-option', (opt) => { document.getElementById('selectedRepeatText').innerText = opt.dataset.repeat === 'none' ? 'Do not repeat' : opt.dataset.repeat; });

    // Date picker change
    document.getElementById('selectedDate')?.addEventListener('change', (e) => {
        currentDate = e.target.value;
        renderCurrentTab();
        if (currentTab === 'calendar') renderCalendarView();
    });

    // Request Time Off button
    document.getElementById('requestTimeOffBtn')?.addEventListener('click', () => {
        window.location.href = 'staff-attendance.html';
    });

    // Escape key to close menus
    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape') {
            closeAllMenus();
            if (document.querySelector('.cancel-modal-overlay')) {
                document.querySelector('.cancel-modal-overlay')?.remove();
                document.body.style.overflow = '';
            }
        }
    });

    // Initialize
    initTabs();
    renderCurrentTab();
</script>

    
    


