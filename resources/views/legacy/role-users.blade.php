    function showActionMenu(userEmail, buttonElement) {
        currentUserForAction = staffData.find(u => u.email === userEmail);
        if (!currentUserForAction) return;

        const rect = buttonElement.getBoundingClientRect();
        const menuWidth = 200; // Approximate width of action menu
        const menuHeight = 280; // Approximate height of action menu (adjust as needed)
        
        // Calculate position
        let top = rect.bottom + window.scrollY + 6;
        let left = rect.left + window.scrollX + (rect.width / 2) - (menuWidth / 2);
        
        // Check if menu goes off-screen to the right
        if (left + menuWidth > window.innerWidth + window.scrollX) {
            left = rect.left + window.scrollX + rect.width - menuWidth;
        }
        
        // Check if menu goes off-screen to the left
        if (left < window.scrollX) {
            left = rect.left + window.scrollX;
        }
        
        // Check if menu goes off-screen at the bottom
        if (top + menuHeight > window.innerHeight + window.scrollY) {
            // Show above the button instead
            top = rect.top + window.scrollY - menuHeight - 6;
        }
        
        actionMenu.style.top = `${top}px`;
        actionMenu.style.left = `${left}px`;
        actionMenu.classList.remove('hidden');
    }

    function hideActionMenu() {
        actionMenu.classList.add('hidden');
