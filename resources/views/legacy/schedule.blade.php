                else if (apt.status === 'Cancelled') bgClass = 'bg-red-500/10';
                
                html += `<div class="rounded text-xs p-1 ${bgClass} cursor-pointer" data-appointment-id="${apt.id}">
                    <div class="truncate">${apt.patientName}</div>
                    <div class="text-[10px] text-muted-foreground truncate">${apt.startTime}</div>
                </div>`;
            });
            if (cellAppointments.length > 3) {
                html += `<div class="text-xs text-center text-muted-foreground">+${cellAppointments.length-3} more</div>`;
            }
            html += `</div></div>`;
            dayCount++;
        }
    }
    html += `</div></div>`;
    container.innerHTML = html;
    attachAppointmentClickEvents(container);
    
    document.getElementById('monthPrevBtn')?.addEventListener('click', () => { currentDate = new Date(year, month-1, 1); updateAllViews(); });
    document.getElementById('monthNextBtn')?.addEventListener('click', () => { currentDate = new Date(year, month+1, 1); updateAllViews(); });
}

// List View
function renderListView() {
    const filtered = getFilteredAppointments(currentDate);
    const container = document.getElementById('listViewPanel');
    if (filtered.length === 0) { container.innerHTML = `<div class="p-8 text-center text-gray-500">No appointments for ${formatDisplayDate(currentDate)}.</div>`; return; }
    let html = `<div class="p-4 border-b"><h2 class="text-xl font-semibold">Appointments List</h2><div class="text-gray-500">All appointments for ${formatDisplayDate(currentDate)} • ${currentDoctorFilter === 'all' ? 'All Doctors' : currentDoctorFilter}</div></div><div class="p-4 space-y-3">`;
    filtered.forEach(apt => {
        html += `<div class="flex items-center justify-between p-2 lg:p-4 border rounded-md" data-appointment-id="${apt.id}">
                    <div class="flex items-center gap-3"><div class="h-2 w-2 rounded-full ${apt.status === 'Completed' ? 'bg-green-500' : apt.status === 'Confirmed' ? 'bg-blue-500' : 'bg-yellow-500'}"></div>
                    <div><p class="font-medium">${apt.patientName}</p><div class="flex items-center text-xs text-gray-500"><svg class="h-3 w-3 mr-1" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="10"></circle><polyline points="12 6 12 12 16 14"></polyline></svg>${apt.startTime} - ${apt.endTime}</div></div></div>
                    <div class="flex items-center gap-4"><div class="flex items-center gap-2"><span class="relative flex shrink-0 overflow-hidden rounded-full h-6 w-6"><img class="aspect-square h-full w-full" src="user.png" alt="User profile photo"></span><span class="text-sm">${apt.doctor}</span></div><div class="status-badge ${getStatusClass(apt.status)}">${apt.status}</div></div>
                </div>`;
    });
    html += `</div>`;
    container.innerHTML = html;
    attachAppointmentClickEvents(container);
}

function attachAppointmentClickEvents(container) {
    container.querySelectorAll('[data-appointment-id]').forEach(el => {
        el.addEventListener('click', (e) => { e.stopPropagation(); const id = parseInt(el.dataset.appointmentId); showActionMenu(el, id); });
    });
}

function showActionMenu(targetElement, aptId) {
    const existing = document.getElementById('actionMenu');
    if (existing) existing.remove();
    const menu = document.createElement('div');
    menu.id = 'actionMenu';
    menu.innerHTML = `<div class="px-2 py-1.5 text-sm font-semibold border-b">Actions</div>
        <div data-action="edit" class="flex items-center gap-2 px-2 py-1.5 text-sm text-gray-700 dark:text-gray-300 hover:bg-gray-100 dark:hover:bg-gray-700 rounded-sm cursor-pointer"><svg class="h-4 w-4" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M12 3H5a2 2 0 0 0-2 2v14a2 2 0 0 0 2 2h14a2 2 0 0 0 2-2v-7"></path><path d="M18.375 2.625a1 1 0 0 1 3 3l-9.013 9.014a2 2 0 0 1-.853.505l-2.873.84a.5.5 0 0 1-.62-.62l.84-2.873a2 2 0 0 1 .506-.852z"></path></svg>Edit</div>
        <div class="border-t my-1"></div>
        <div data-action="delete" class="flex items-center gap-2 px-2 py-1.5 text-sm text-red-600 hover:bg-red-50 dark:hover:bg-red-900/30 rounded-sm cursor-pointer"><svg class="h-4 w-4" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M3 6h18"></path><path d="M19 6v14c0 1-1 2-2 2H7c-1 0-2-1-2-2V6"></path><path d="M8 6V4c0-1 1-2 2-2h4c1 0 2 1 2 2v2"></path></svg>Delete</div>`;
    const rect = targetElement.getBoundingClientRect();
    menu.style.left = `${rect.right - 160}px`;
    menu.style.top = `${rect.bottom + 5}px`;
    document.body.appendChild(menu);
    const closeMenu = (e) => { if (!menu.contains(e.target) && e.target !== targetElement) { menu.remove(); document.removeEventListener('click', closeMenu); } };
    setTimeout(() => document.addEventListener('click', closeMenu), 10);
    menu.querySelectorAll('[data-action]').forEach(btn => {
        btn.addEventListener('click', (e) => {
            if (btn.dataset.action === 'edit') alert(`✏️ Edit appointment ID ${aptId} (Demo)`);
            if (btn.dataset.action === 'delete') { if (confirm('Delete this appointment?')) { appointments = appointments.filter(a => a.id !== aptId); updateAllViews(); } }
            menu.remove();
        });
    });
}

function updateAllViews() {
    renderCalendar();
    if (currentTab === 'day') renderDayView();
    else if (currentTab === 'week') renderWeekView();
    else if (currentTab === 'month') renderMonthView();
    else if (currentTab === 'list') renderListView();
    document.getElementById('currentDateDisplay').innerText = formatDisplayDate(currentDate);
}

// Tab switching
function initTabs() {
    const tabs = document.querySelectorAll('.schedule-tab');
    const panels = { day: document.getElementById('dayViewPanel'), week: document.getElementById('weekViewPanel'), month: document.getElementById('monthViewPanel'), list: document.getElementById('listViewPanel') };
    tabs.forEach(tab => {
        tab.addEventListener('click', () => {
            const tabId = tab.dataset.tab;
            currentTab = tabId;
            tabs.forEach(t => { t.classList.remove('bg-white', 'text-indigo-700', 'shadow-sm'); t.classList.add('text-gray-600'); });
            tab.classList.add('bg-white', 'text-indigo-700', 'shadow-sm');
            Object.keys(panels).forEach(key => panels[key].classList.remove('active'));
            panels[tabId].classList.add('active');
            updateAllViews();
        });
    });
}

// Doctor filter dropdown
function initDoctorSelect() {
    const trigger = document.getElementById('doctorSelectTrigger');
    const dropdown = document.getElementById('doctorSelectDropdown');
    trigger.addEventListener('click', (e) => { e.stopPropagation(); dropdown.classList.toggle('hidden'); });
    document.querySelectorAll('.doctor-option').forEach(opt => {
        opt.addEventListener('click', () => {
            currentDoctorFilter = opt.dataset.value;
            document.getElementById('selectedDoctorText').innerText = opt.innerText;
            dropdown.classList.add('hidden');
            updateAllViews();
        });
    });
    document.addEventListener('click', (e) => { if (!trigger.contains(e.target) && !dropdown.contains(e.target)) dropdown.classList.add('hidden'); });
}

