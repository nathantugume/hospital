function openDeleteModal(id, name) {
    pendingDeleteId = id;
    const deleteModal = document.getElementById('deleteModal');
    const deleteSpecNameDisplay = document.getElementById('deleteSpecNameDisplay');
    const deleteWarningMessage = document.getElementById('deleteWarningMessage');
    
    // Find the specialization to get doctor count
    const spec = specializationsData.find(s => s.id === id);
    if (spec) {
        deleteSpecNameDisplay.textContent = `"${escapeHtml(spec.name)}"`;
        
        // Add warning if there are doctors associated
        if (spec.doctors > 0) {
            deleteWarningMessage.textContent = `Warning: This specialization has ${spec.doctors} doctor${spec.doctors !== 1 ? 's' : ''} associated with it. Deleting it may affect doctor profiles and assignments.`;
