        }

        function renderStatsCards() {
            const statsContainer = document.getElementById('statsCardsContainer');
            if (!statsContainer) return;
            const sorted = [...specializationsData].sort((a,b) => b.doctors - a.doctors).slice(0,4);
            const maxDoctors = Math.max(...sorted.map(s => s.doctors), 1);
            let cardsHtml = '';
            sorted.forEach(spec => {
                const percentage = (spec.doctors / maxDoctors) * 100;
                cardsHtml += `<div class="rounded-lg border bg-background shadow-sm p-4"><h3 class="font-semibold">${escapeHtml(spec.name)}</h3><div class="text-2xl font-bold mt-2">${spec.doctors}</div><p class="text-xs text-gray-500">Doctors</p><div class="mt-2 h-1.5 w-full bg-gray-100 rounded-full overflow-hidden"><div class="h-full bg-primary rounded-full" style="width: ${percentage}%;"></div></div></div>`;
            });
            statsContainer.innerHTML = cardsHtml;
        }

        // Search
        document.getElementById('searchSpecialization')?.addEventListener('input', (e) => { currentSearch = e.target.value; renderSpecializationsTable(); });

        // Add Modal
        const addModal = document.getElementById('addSpecializationModal');
        function openAddModal() { addModal.classList.remove('hidden'); }
        function closeAddModal() { addModal.classList.add('hidden'); 
            document.getElementById('addSpecName').value = '';
            document.getElementById('addSpecDescription').value = '';
            document.getElementById('addSpecDepartment').value = '';
            document.getElementById('addSpecDoctors').value = '0';
        }
        document.getElementById('addSpecializationBtn')?.addEventListener('click', openAddModal);
        document.getElementById('cancelSpecBtn')?.addEventListener('click', closeAddModal);
        document.getElementById('closeSpecModalBtn')?.addEventListener('click', closeAddModal);
        addModal?.addEventListener('click', (e) => { if (e.target === addModal) closeAddModal(); });
        
        document.getElementById('saveSpecBtn')?.addEventListener('click', () => {
            const name = document.getElementById('addSpecName').value.trim();
            const desc = document.getElementById('addSpecDescription').value.trim() || 'No description';
            const dept = document.getElementById('addSpecDepartment').value.trim();
            const doctors = parseInt(document.getElementById('addSpecDoctors').value) || 0;
            if (!name || !dept) { showToast('Name and Department are required', 'error'); return; }
            if (specializationsData.some(s => s.name.toLowerCase() === name.toLowerCase())) { showToast('Specialization already exists', 'error'); return; }
            const newId = Math.max(...specializationsData.map(s => s.id), 0) + 1;
            specializationsData.push({ id: newId, name, description: desc, doctors, department: dept, status: 'Active' });
            saveSpecializationsToStorage();
            renderSpecializationsTable();
            renderStatsCards();
            showToast(`Specialization "${name}" added successfully!`, 'success');
            closeAddModal();
        });

        // Delete Modal Event Listeners
        document.getElementById('cancelDeleteBtn')?.addEventListener('click', closeDeleteModal);
        document.getElementById('confirmDeleteBtn')?.addEventListener('click', confirmDelete);
        document.getElementById('deleteModal')?.addEventListener('click', (e) => { if (e.target === document.getElementById('deleteModal')) closeDeleteModal(); });

        // Close modals on Escape
        document.addEventListener('keydown', (e) => {
            if (e.key === 'Escape') {
                closeAddModal();
                closeDeleteModal();
                closeActionMenu();
            }
        });

        // Check for updated data from edit page
        const updatedSpec = sessionStorage.getItem('updatedSpecialization');
        if (updatedSpec) {
            try {
                const updated = JSON.parse(updatedSpec);
                const index = specializationsData.findIndex(s => s.id === updated.id);
                if (index !== -1) { specializationsData[index] = updated; saveSpecializationsToStorage(); showToast(`Specialization "${updated.name}" updated successfully!`, 'success'); renderSpecializationsTable(); renderStatsCards(); }
                sessionStorage.removeItem('updatedSpecialization');
            } catch(e) {}
        }

        window.addEventListener('storage', (e) => { if (e.key === 'meditrack_specializations') { loadSpecializationsFromStorage(); renderSpecializationsTable(); renderStatsCards(); } });

        // Initialize
        loadSpecializationsFromStorage();
        renderSpecializationsTable();
        renderStatsCards();
    </script>

    
    


