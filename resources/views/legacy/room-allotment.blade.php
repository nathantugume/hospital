    // Radix UI Style Select Component
    class RadixSelect {
        constructor(containerId, options, placeholder, onChange) {
            this.container = document.getElementById(containerId);
            this.options = options;
            this.placeholder = placeholder;
            this.onChange = onChange;
            this.selectedValue = '';
            this.selectedLabel = placeholder;
            this.isOpen = false;
            this.render();
        }
        render() {
            this.container.innerHTML = `<button type="button" class="custom-select-trigger" data-state="closed"><span class="flex-1 text-left">${this.selectedLabel}</span><svg class="h-4 w-4 opacity-50 transition-transform" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><polyline points="6 9 12 15 18 9"></polyline></svg></button>`;
            this.trigger = this.container.querySelector('.custom-select-trigger');
            this.trigger.addEventListener('click', (e) => { e.stopPropagation(); this.toggle(); });
        }
        toggle() { this.isOpen ? this.close() : this.open(); }
        open() {
            if (this.menu) this.menu.remove();
            const rect = this.trigger.getBoundingClientRect();
            this.menu = document.createElement('div');
            this.menu.className = 'custom-select-content';
            this.menu.style.minWidth = `${rect.width}px`;
            this.menu.style.top = `${rect.bottom + 4}px`;
            this.menu.style.left = `${rect.left}px`;
            this.menu.innerHTML = `<div class="py-1">${this.options.map(opt => `<div class="custom-select-item" data-value="${opt.value}" data-label="${opt.label}">${opt.label}</div>`).join('')}</div>`;
            document.body.appendChild(this.menu);
            this.isOpen = true;
            this.trigger.setAttribute('data-state', 'open');
            this.trigger.querySelector('svg').style.transform = 'rotate(180deg)';
            this.menu.querySelectorAll('.custom-select-item').forEach(item => {
                item.addEventListener('click', () => {
                    this.setValue(item.dataset.value, item.dataset.label);
                    this.close();
                });
            });
            const closeHandler = (e) => { if (!this.menu.contains(e.target) && e.target !== this.trigger) this.close(); };
            setTimeout(() => document.addEventListener('click', closeHandler), 10);
            this.closeHandler = closeHandler;
        }
        setValue(value, label) {
            this.selectedValue = value;
            this.selectedLabel = label;
            this.trigger.querySelector('.flex-1').textContent = label;
            if (this.onChange) this.onChange(value);
        }
        close() {
            if (this.menu) { this.menu.remove(); this.menu = null; }
            this.isOpen = false;
            this.trigger.setAttribute('data-state', 'closed');
            if (this.trigger.querySelector('svg')) this.trigger.querySelector('svg').style.transform = '';
            if (this.closeHandler) document.removeEventListener('click', this.closeHandler);
        }
        getValue() { return this.selectedValue; }
    }

