    class DatePicker {
        constructor(containerId, placeholder, onChange) {
            this.container = document.getElementById(containerId);
            this.placeholder = placeholder;
            this.onChange = onChange;
            this.value = '';
            this.render();
        }
        render() {
            this.container.innerHTML = `<button type="button" class="date-trigger" id="${this.container.id}-btn"><span class="flex-1 text-left">${this.placeholder}</span><svg class="h-4 w-4 opacity-50" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M8 2v4"/><path d="M16 2v4"/><rect width="18" height="18" x="3" y="4" rx="2"/><path d="M3 10h18"/></svg></button>`;
            this.btn = document.getElementById(`${this.container.id}-btn`);
            this.btn.addEventListener('click', () => this.openPicker());
        }
        openPicker() {
            flatpickr(this.btn, {
                dateFormat: "Y-m-d",
                onChange: (selectedDates, dateStr) => {
                    this.value = dateStr;
                    this.btn.querySelector('.flex-1').textContent = dateStr || this.placeholder;
                    if (this.onChange) this.onChange(dateStr);
                }
            }).open();
        }
        getValue() { return this.value; }
    }

