function initializePage() {
    const today = new Date().toISOString().split('T')[0];
    document.getElementById('dispatchDate').value = today;
    document.getElementById('dispatchDate').setAttribute('min', today);

    // Set default estimated delivery to 2 hours from now
    const now = new Date();
    now.setHours(now.getHours() + 2);
    const hours = String(now.getHours()).padStart(2, '0');
    const minutes = String(now.getMinutes()).padStart(2, '0');
    document.getElementById('estimatedDelivery').value = `${hours}:${minutes}`;

    // Check URL params for transfer ID
    const urlParams = new URLSearchParams(window.location.search);
    const transferId = urlParams.get('id');
    if (transferId) {
        document.getElementById('dispatchTransferId').textContent = transferId;
        console.log('Dispatching transfer:', transferId);
    }

    updateDispatchSummary();
}

