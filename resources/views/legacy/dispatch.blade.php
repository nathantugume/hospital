        const qty = parseInt(row.querySelector('.dispatch-qty').value) || 0;
        const unit = row.cells[5].textContent.trim();
        if (name && qty > 0) {
            items.push({ name, batch, qty, unit });
        }
    });

    const summaryContent = document.getElementById('dispatchSummaryContent');
