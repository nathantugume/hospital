// ==================== TOAST ====================
function showToast(message, isError = false) {
    const existing = document.querySelector('.toast-message');
    if (existing) existing.remove();
    const toast = document.createElement('div');
    toast.className = `fixed bottom-5 right-5 px-5 py-3 rounded-lg text-sm text-white shadow-lg z-[11000] animate-slide-in ${isError ? 'bg-red-500' : 'bg-emerald-500'}`;
    toast.textContent = message;
    document.body.appendChild(toast);
    setTimeout(() => toast.remove(), 3000);
}

// ==================== RADIX-STYLE SELECT ====================
function initRadixSelect(triggerId, dropdownId, hiddenInputId) {
    const trigger = document.getElementById(triggerId);
    const dropdown = document.getElementById(dropdownId);
    const hiddenInput = document.getElementById(hiddenInputId);
    if (!trigger || !dropdown) return;

    const valueSpan = trigger.querySelector('[data-radix-select-value]');

    trigger.addEventListener('click', (e) => {
        e.stopPropagation();
        const isOpen = !dropdown.classList.contains('hidden');
        closeAllDropdowns();
        if (!isOpen) dropdown.classList.remove('hidden');
    });

    dropdown.querySelectorAll('[data-radix-select-item]').forEach(item => {
        item.addEventListener('click', () => {
            const value = item.dataset.value;
            if (valueSpan) valueSpan.textContent = item.textContent;
            if (hiddenInput) hiddenInput.value = value;
            trigger.removeAttribute('data-placeholder');
            
            dropdown.querySelectorAll('[data-radix-select-item]').forEach(i => i.removeAttribute('data-state'));
            item.setAttribute('data-state', 'checked');
            
            dropdown.classList.add('hidden');
            updateDispatchSummary();
        });
    });

    document.addEventListener('click', (e) => {
        if (!trigger.contains(e.target) && !dropdown.contains(e.target)) {
            dropdown.classList.add('hidden');
        }
    });
}

function closeAllDropdowns() {
    document.querySelectorAll('[data-radix-select-content]').forEach(d => d.classList.add('hidden'));
}

// Initialize Radix select
initRadixSelect('transportMethodTrigger', 'transportMethodDropdown', 'transportMethod');

// ==================== CHECKBOX ====================
function initRadixCheckbox(checkboxId, labelId) {
    const checkbox = document.getElementById(checkboxId);
    const label = document.getElementById(labelId);
    if (!checkbox) return;

    function toggle() {
        const isChecked = checkbox.getAttribute('data-state') === 'checked';
        checkbox.setAttribute('data-state', isChecked ? 'unchecked' : 'checked');
    }

    checkbox.addEventListener('click', toggle);
    if (label) label.addEventListener('click', toggle);
}

initRadixCheckbox('urgentDispatchCheckbox', 'urgentDispatchLabel');
initRadixCheckbox('notifyReceiverCheckbox', 'notifyReceiverLabel');

// ==================== DISPATCH QUANTITY VALIDATION ====================
document.querySelectorAll('.dispatch-qty').forEach(input => {
    input.addEventListener('input', function() {
        const max = parseInt(this.dataset.approved) || 0;
        let val = parseInt(this.value) || 0;
        if (val > max) {
            this.value = max;
            showToast(`Cannot exceed approved quantity of ${max}`, true);
        }
        if (val < 0) {
            this.value = 0;
        }
        updateDispatchSummary();
    });

    input.addEventListener('change', updateDispatchSummary);
});

