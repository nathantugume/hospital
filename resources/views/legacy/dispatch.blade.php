// ==================== VALIDATION ====================
function validateDispatchForm() {
    const errors = [];
    const dispatchedBy = document.getElementById('dispatchedBy').value.trim();
    const dispatchDate = document.getElementById('dispatchDate').value;
    const transportMethod = document.getElementById('transportMethod').value;

    if (!dispatchedBy) errors.push('Dispatched By is required');
    if (!dispatchDate) errors.push('Dispatch Date is required');
    if (!transportMethod) errors.push('Transport Method is required');

    let totalQty = 0;
    document.querySelectorAll('.dispatch-qty').forEach(input => {
        totalQty += parseInt(input.value) || 0;
    });

    if (totalQty === 0) {
        errors.push('At least one item must have a dispatch quantity greater than 0');
    }

    return errors;
}

