        </tr>
    `;
    
    const renderSimpleRow = (service) => `
        <tr class="border-b  hover:bg-accent hover:text-accent-foreground h-10 dark:hover:bg-gray-800">
            <td class="p-4 font-medium">${service.name}</td>
            <td class="p-4">${service.department}</td>
            <td class="p-4 hidden md:table-cell">${service.duration}</td>
            <td class="p-4 hidden md:table-cell">$${service.price}</td>
            <td class="p-4 text-right"><button data-id="${service.id}" data-name="${service.name}" class="action-trigger inline-flex items-center justify-center h-10 w-10 rounded-md hover:bg-gray-100"><svg class="h-4 w-4 text-gray-500" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="1"/><circle cx="19" cy="12" r="1"/><circle cx="5" cy="12" r="1"/></svg></button></td>
        </tr>
    `;
    
    if (currentTab === "all") {
        document.getElementById('allTableBody').innerHTML = paginatedData.map(renderRow).join('');
        document.getElementById('paginationInfo').innerHTML = `Showing <strong>${paginatedData.length}</strong> of <strong>${totalItems}</strong> services`;
        document.getElementById('prevPageBtn').disabled = currentPage === 1;
        document.getElementById('nextPageBtn').disabled = currentPage === totalPages || totalPages === 0;
    }
    
    const diagnosticData = allServices.filter(s => s.type === "Diagnostic");
    const treatmentData = allServices.filter(s => s.type === "Treatment");
    const preventiveData = allServices.filter(s => s.type === "Preventive");
    
    document.getElementById('diagnosticTableBody').innerHTML = diagnosticData.map(renderSimpleRow).join('');
    document.getElementById('treatmentTableBody').innerHTML = treatmentData.map(renderSimpleRow).join('');
    document.getElementById('preventiveTableBody').innerHTML = preventiveData.map(renderSimpleRow).join('');
    document.getElementById('allCount').innerHTML = `Showing ${paginatedData.length} of ${totalItems} services`;
    document.getElementById('totalServicesCount').innerHTML = allServices.length;
    
    document.querySelectorAll('.action-trigger').forEach(btn => {
        btn.addEventListener('click', (e) => { e.stopPropagation(); showActionMenu(btn, btn.dataset.id, btn.dataset.name); });
    });
}

// Tab switching
const tabs = ['all', 'diagnostic', 'treatment', 'preventive'];
function activateTab(tabId) {
    currentTab = tabId;
    currentPage = 1;
    tabs.forEach(t => { 
        const panel = document.getElementById(`tab-${t}`); 
        const btn = document.querySelector(`[data-tab="${t}"]`); 
        if(panel) panel.classList.add('hidden'); 
        if(btn) { 
            btn.setAttribute('data-state', t === tabId ? 'active' : 'inactive'); 
            if(t === tabId) btn.classList.add('bg-white', 'text-gray-900', 'shadow-sm'); 
            else btn.classList.remove('bg-white', 'text-gray-900', 'shadow-sm'); 
        } 
    });
    document.getElementById(`tab-${tabId}`)?.classList.remove('hidden');
    renderAllTables();
}
document.querySelectorAll('.tab-btn').forEach(btn => btn.addEventListener('click', () => activateTab(btn.dataset.tab)));

