        <div role="alertdialog" class="fixed left-[50%] top-[50%] z-50 grid w-full max-w-lg translate-x-[-50%] translate-y-[-50%] gap-4 border bg-background p-6 shadow-lg duration-200 data-[state=open]:animate-in data-[state=closed]:animate-out data-[state=closed]:fade-out-0 data-[state=open]:fade-in-0 data-[state=closed]:zoom-out-95 data-[state=open]:zoom-in-95 data-[state=closed]:slide-out-to-left-1/2 data-[state=closed]:slide-out-to-top-[48%] data-[state=open]:slide-in-from-left-1/2 data-[state=open]:slide-in-from-top-[48%] sm:rounded-lg">
            <div class="flex flex-col space-y-2 text-center sm:text-left">
                <h2 class="text-lg font-semibold">${title}</h2>
                <p class="text-sm text-muted-foreground">${message}</p>
            </div>
            <div class="flex flex-col-reverse sm:flex-row sm:justify-end sm:space-x-2">
                <button type="button" class="cancel-delete-btn inline-flex items-center justify-center shrink-0 gap-2 whitespace-nowrap rounded-md text-sm font-medium ring-offset-background transition-colors focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-2 disabled:pointer-events-none disabled:opacity-50 border border-input bg-background hover:bg-accent hover:text-accent-foreground h-10 px-4 py-2 mt-2 sm:mt-0">Cancel</button>
                <button type="button" class="confirm-delete-btn inline-flex items-center justify-center shrink-0 gap-2 whitespace-nowrap rounded-md text-sm font-medium ring-offset-background transition-colors focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-2 disabled:pointer-events-none disabled:opacity-50 h-10 px-4 py-2 bg-red-500 text-neutral-50 hover:bg-red-700">Delete</button>
            </div>
        </div>
    `;
    
    document.body.appendChild(modalOverlay);
    activeDeleteModal = modalOverlay;
    currentDeleteCallback = onConfirm;
    
    // Close modal function
    const closeModal = () => {
        if (activeDeleteModal) {
            activeDeleteModal.remove();
            activeDeleteModal = null;
            currentDeleteCallback = null;
        }
    };
    
    // Cancel button
    const cancelBtn = modalOverlay.querySelector('.cancel-delete-btn');
    cancelBtn?.addEventListener('click', closeModal);
    
    // Confirm button
    const confirmBtn = modalOverlay.querySelector('.confirm-delete-btn');
    confirmBtn?.addEventListener('click', () => {
        if (currentDeleteCallback) {
            currentDeleteCallback();
        }
        closeModal();
    });
    
    // Click outside to close
    modalOverlay.addEventListener('click', (e) => {
        if (e.target === modalOverlay) closeModal();
    });
    
    // Escape key to close
    const escapeHandler = (e) => {
        if (e.key === 'Escape') {
            closeModal();
            document.removeEventListener('keydown', escapeHandler);
        }
    };
    document.addEventListener('keydown', escapeHandler);
}

// Delete service function
function deleteService(serviceId) {
    const index = allServices.findIndex(s => s.id == serviceId);
    if (index !== -1) {
        const deleted = allServices.splice(index, 1)[0];
        renderAllTables();
        showToast(`"${deleted.name}" has been deleted successfully`);
    }
}

// Toast function
function showToast(message, isError = false) {
    const existing = document.querySelector('.toast-message');
    if (existing) existing.remove();
    const toast = document.createElement('div');
    toast.className = `toast-message ${isError ? 'error' : ''}`;
    toast.textContent = message;
    document.body.appendChild(toast);
    setTimeout(() => toast.remove(), 3000);
}

function getFilteredData() {
    let filtered = [...allServices];
    if (currentTab !== "all") filtered = filtered.filter(s => s.type.toLowerCase() === currentTab);
    if (deptFilter !== "all") filtered = filtered.filter(s => s.department === deptFilter);
    if (searchQuery) filtered = filtered.filter(s => s.name.toLowerCase().includes(searchQuery) || s.department.toLowerCase().includes(searchQuery));
    if (sortBy === "price_asc") filtered.sort((a,b) => a.price - b.price);
    else if (sortBy === "price_desc") filtered.sort((a,b) => b.price - a.price);
    else if (sortBy === "duration_asc") filtered.sort((a,b) => parseInt(a.duration) - parseInt(b.duration));
    else if (sortBy === "duration_desc") filtered.sort((a,b) => parseInt(b.duration) - parseInt(a.duration));
    else if (sortBy === "popularity") filtered.sort((a,b) => b.popularity - a.popularity);
    return filtered;
}

function renderAllTables() {
    const filteredData = getFilteredData();
    const totalItems = filteredData.length;
    const totalPages = Math.ceil(totalItems / itemsPerPage);
