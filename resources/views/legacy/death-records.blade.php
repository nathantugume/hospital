            case 'verify':
                if (record.status === "Pending") {
                    record.status = "Verified";
                    renderAllTables();
                    showToast(`✅ ${record.id} verified successfully`);
                } else {
                    showToast("Record is already verified");
                }
                break;
        }
        closeActionMenu();
    }

    function showActionMenu(anchor, record) {
        closeActionMenu();
        const menu = document.getElementById('actionDropdown');
        const rect = anchor.getBoundingClientRect();
        let left = rect.right - 190, top = rect.bottom + 6;
        if(left < 10) left = 10;
        if(top + 200 > window.innerHeight) top = rect.top - 200;
        menu.style.left = `${left}px`; 
        menu.style.top = `${top}px`;
        menu.classList.add('show'); 
        activeDropdown = menu;
        
        // Update verify button
        const verifyBtn = menu.querySelector('[data-action="verify"]');
        if (verifyBtn) {
            if (record.status === "Verified") {
                verifyBtn.innerHTML = `<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M20 13c0 5-3.5 7.5-7.66 8.95a1 1 0 0 1-.67-.01C7.5 20.5 4 18 4 13V6a1 1 0 0 1 1-1c2 0 4.5-1.2 6.24-2.72a1.17 1.17 0 0 1 1.52 0C14.51 3.81 17 5 19 5a1 1 0 0 1 1 1z"/><path d="m9 12 2 2 4-4"/></svg>Already Verified`;
                verifyBtn.style.opacity = '0.6';
                verifyBtn.style.cursor = 'default';
            } else {
                verifyBtn.innerHTML = `<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M20 13c0 5-3.5 7.5-7.66 8.95a1 1 0 0 1-.67-.01C7.5 20.5 4 18 4 13V6a1 1 0 0 1 1-1c2 0 4.5-1.2 6.24-2.72a1.17 1.17 0 0 1 1.52 0C14.51 3.81 17 5 19 5a1 1 0 0 1 1 1z"/><path d="m9 12 2 2 4-4"/></svg>Verify Record`;
                verifyBtn.style.opacity = '1';
                verifyBtn.style.cursor = 'pointer';
            }
        }
        
        // Clone menu items to remove stale listeners
        const menuItems = menu.querySelectorAll('.action-menu-item');
        menuItems.forEach(item => {
            const newItem = item.cloneNode(true);
            item.parentNode.replaceChild(newItem, item);
        });
        
        // Re-attach handlers
        menu.querySelectorAll('.action-menu-item').forEach(item => {
            item.addEventListener('click', (e) => {
                e.stopPropagation();
                const action = item.dataset.action;
                if (action === 'verify' && record.status === 'Verified') {
                    showToast("Record is already verified");
                    closeActionMenu();
                    return;
                }
                handleAction(action, record);
            });
        });
        
        const outside = (e) => { 
            if(!menu.contains(e.target) && !anchor.contains(e.target)) { 
                closeActionMenu(); 
                document.removeEventListener('click', outside); 
            } 
        };
        setTimeout(() => document.addEventListener('click', outside), 10);
    }

    // ============ FILTER DROPDOWNS ============
    function setupDropdown(btnId, menuId, spanId, updateKey) {
        const btn = document.getElementById(btnId);
        const menu = document.getElementById(menuId);
        const span = document.getElementById(spanId);
        if (!btn || !menu) return;
        
        btn.addEventListener('click', (e) => {
            e.stopPropagation();
            document.querySelectorAll('.filter-dropdown-menu').forEach(m => {
                if (m !== menu) m.classList.add('hidden');
            });
            menu.classList.toggle('hidden');
        });
        
        menu.querySelectorAll('.filter-option').forEach(opt => {
            opt.addEventListener('click', (e) => {
                e.stopPropagation();
                const value = opt.dataset.value;
                span.innerText = opt.innerText;
                filterOptions[updateKey] = value;
                menu.classList.add('hidden');
            });
        });
    }

    setupDropdown('statusDropdownBtn', 'statusDropdownMenu', 'selectedStatusText', 'status');
    setupDropdown('locationDropdownBtn', 'locationDropdownMenu', 'selectedLocationText', 'location');
    setupDropdown('doctorDropdownBtn', 'doctorDropdownMenu', 'selectedDoctorText', 'doctor');

    document.addEventListener('click', (e) => {
        if (!e.target.closest('.filter-select-trigger') && !e.target.closest('.filter-dropdown-menu')) {
            document.querySelectorAll('.filter-dropdown-menu').forEach(m => m.classList.add('hidden'));
        }
    });

    // ============ DATE PICKER ============
    function updateDateDisplay() {
        const span = document.getElementById('dateRangeDisplay');
        if (dateRange.start && dateRange.end) span.innerText = `${dateRange.start} – ${dateRange.end}`;
        else if (dateRange.start) span.innerText = `From ${dateRange.start}`;
        else if (dateRange.end) span.innerText = `Until ${dateRange.end}`;
        else span.innerText = "All Dates";
    }

    document.getElementById('dateRangeBtn')?.addEventListener('click', (e) => {
        e.stopPropagation();
        const popover = document.getElementById('datePickerPopover');
        const isHidden = popover.classList.contains('hidden');
        popover.classList.toggle('hidden');
        if (isHidden && dateRange.start) document.getElementById('radixStart').value = dateRange.start;
        if (isHidden && dateRange.end) document.getElementById('radixEnd').value = dateRange.end;
    });

    document.getElementById('radixApply')?.addEventListener('click', () => {
        dateRange.start = document.getElementById('radixStart').value;
        dateRange.end = document.getElementById('radixEnd').value;
        updateDateDisplay();
        renderAllTables();
        document.getElementById('datePickerPopover').classList.add('hidden');
        if (dateRange.start || dateRange.end) showToast("Date range applied");
    });

    document.getElementById('radixCancel')?.addEventListener('click', () => {
        document.getElementById('datePickerPopover').classList.add('hidden');
        if (dateRange.start) document.getElementById('radixStart').value = dateRange.start;
        if (dateRange.end) document.getElementById('radixEnd').value = dateRange.end;
    });

    document.addEventListener('click', (e) => {
        const popover = document.getElementById('datePickerPopover');
        const dateBtn = document.getElementById('dateRangeBtn');
        if (popover && !popover.classList.contains('hidden')) {
            if (!popover.contains(e.target) && !dateBtn.contains(e.target)) {
                popover.classList.add('hidden');
            }
        }
    });

    // ============ EVENT LISTENERS ============
    document.getElementById('searchInput')?.addEventListener('input', (e) => { searchQuery = e.target.value; renderAllTables(); });
    document.getElementById('exportBtn')?.addEventListener('click', exportToCSV);
    document.getElementById('addRecordBtn')?.addEventListener('click', () => { window.location.href = 'add-death-records.html'; });
    
    document.getElementById('filterPushBtn')?.addEventListener('click', () => { 
        const card = document.getElementById('filterPushCard'); 
        card.classList.toggle('hidden-card'); 
    });
    
    document.getElementById('applyFiltersBtn')?.addEventListener('click', () => { 
        renderAllTables(); 
        showToast("Filters applied"); 
    });
    
    document.getElementById('resetFiltersBtn')?.addEventListener('click', () => {
        filterOptions = { status: "", location: "", doctor: "" };
        dateRange = { start: "", end: "" };
        searchQuery = "";
        document.getElementById('searchInput').value = "";
        document.getElementById('selectedStatusText').innerText = "All Statuses";
        document.getElementById('selectedLocationText').innerText = "All Locations";
        document.getElementById('selectedDoctorText').innerText = "All Doctors";
        updateDateDisplay();
        renderAllTables();
        showToast("Filters reset");
    });

    // Tabs
    document.querySelectorAll('.tab-btn').forEach(btn => { 
        btn.addEventListener('click', () => { 
            currentTab = btn.dataset.tab; 
            document.querySelectorAll('.tab-btn').forEach(b => b.setAttribute('data-state', b.dataset.tab === currentTab ? 'active' : 'inactive')); 
            document.querySelectorAll('[role="tabpanel"]').forEach(panel => panel.setAttribute('data-state', panel.id === `tab-${currentTab}` ? 'active' : 'inactive')); 
            renderAllTables(); 
        }); 
    });

    // Escape to close
    document.addEventListener('keydown', (e) => { if(e.key === 'Escape') { closeActionMenu(); document.getElementById('datePickerPopover')?.classList.add('hidden'); } });

    // Initialize
    renderAllTables();
