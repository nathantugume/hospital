function openEmailModal() {
    emailModal.style.display = 'flex';
    document.body.style.overflow = 'hidden';
}

function closeEmailModal() {
    emailModal.style.display = 'none';
    document.body.style.overflow = '';
    emailError.style.display = 'none';
}

function validateEmail(email) {
    const re = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    return re.test(email);
}

function sendEmail() {
    const email = recipientEmail.value.trim();
    
    if (!validateEmail(email)) {
        emailError.style.display = 'block';
        return;
    }
    
    emailError.style.display = 'none';
    
    // Disable button and show loading
    sendEmailBtn.disabled = true;
    sendEmailBtn.textContent = 'Sending...';
    
    // Simulate email sending with delay
    setTimeout(() => {
        if (attachPDF.checked) {
            // Generate PDF and "send" it
            const element = document.getElementById('receiptContent');
            const printHeaders = document.querySelectorAll('.print-only-header, .print-only-footer');
            printHeaders.forEach(el => el.classList.remove('hidden'));
            
            const opt = {
                margin: [0.5, 0.5, 0.5, 0.5],
                filename: `Receipt_PMT-007.pdf`,
                image: { type: 'jpeg', quality: 0.98 },
                html2canvas: { scale: 2, logging: false, useCORS: true },
                jsPDF: { unit: 'in', format: 'letter', orientation: 'portrait' }
            };
            
            html2pdf().set(opt).from(element).outputPdf().then((pdf) => {
                // Simulate successful email with attachment
                console.log('PDF generated for attachment');
                showToast(`✓ Receipt sent to ${email} with PDF attachment`, 'green');
                printHeaders.forEach(el => el.classList.add('hidden'));
                closeEmailModal();
                sendEmailBtn.disabled = false;
                sendEmailBtn.textContent = 'Send Email';
            }).catch(() => {
                showToast('Error generating PDF attachment', 'red');
                sendEmailBtn.disabled = false;
                sendEmailBtn.textContent = 'Send Email';
                printHeaders.forEach(el => el.classList.add('hidden'));
            });
        } else {
            // Just send email without attachment
            showToast(`✓ Receipt sent to ${email}`, 'green');
            closeEmailModal();
            sendEmailBtn.disabled = false;
            sendEmailBtn.textContent = 'Send Email';
        }
    }, 1500);
}

