// ==================== SUMMARY ====================
function updateSummary() {
    const items = [];
    document.querySelectorAll('.item-row').forEach(row => {
        const name = row.querySelector('.item-name').value.trim();
        const qty = parseInt(row.querySelector('.item-qty').value) || 0;
        const unit = row.querySelector('.item-unit').value;
        const batch = row.querySelector('.item-batch').value.trim();
        if (name && qty > 0) {
            items.push({ name, qty, unit, batch });
        }
    });

    const summarySection = document.getElementById('summarySection');
    const summaryContent = document.getElementById('summaryContent');

    if (items.length === 0) {
        summarySection.style.display = 'none';
        return;
    }

    summarySection.style.display = 'block';
    const totalItems = items.length;
    const totalQty = items.reduce((sum, item) => sum + item.qty, 0);

    let html = '';
    items.forEach((item, index) => {
        html += `
            <div class="flex justify-between py-1.5 text-sm">
                <span>${index + 1}. <strong>${item.name}</strong> ${item.batch ? `(Batch: ${item.batch})` : ''}</span>
                <span class="text-gray-600">${item.qty} ${item.unit}</span>
            </div>`;
    });
    html += `<div class="border-t border-dashed border-gray-200 my-2"></div>`;
    html += `
        <div class="flex justify-between py-1.5 text-sm font-semibold">
            <span>Total Items</span>
            <span>${totalItems} item${totalItems > 1 ? 's' : ''}</span>
        </div>
        <div class="flex justify-between py-1.5 text-sm font-semibold">
            <span>Total Quantity</span>
            <span>${totalQty} units</span>
        </div>`;

    summaryContent.innerHTML = html;
}

// ==================== VALIDATION ====================
function validateForm() {
    const errors = [];
    const transferType = document.getElementById('transferType').value;
    const priority = document.getElementById('priority').value;
    const source = document.getElementById('sourceLocation').value;
    const dest = document.getElementById('destLocation').value;
    const requestedBy = document.getElementById('requestedBy').value.trim();
    const reason = document.getElementById('transferReason').value.trim();

    if (!transferType) errors.push('Transfer Type is required');
    if (!priority) errors.push('Priority Level is required');
    if (!source) errors.push('Source Location is required');
    if (!dest) errors.push('Destination Location is required');
    if (source && dest && source === dest) errors.push('Source and Destination cannot be the same');
    if (!requestedBy) errors.push('Requested By is required');
    if (!reason) errors.push('Reason for Transfer is required');

    const items = [];
    document.querySelectorAll('.item-row').forEach(row => {
        const name = row.querySelector('.item-name').value.trim();
        const qty = parseInt(row.querySelector('.item-qty').value) || 0;
        if (name) items.push({ name, qty });
    });

    if (items.length === 0) {
        errors.push('At least one item with a name and quantity is required');
    } else {
        items.forEach((item, i) => {
            if (!item.name) errors.push(`Item #${i + 1}: Name is required`);
            if (!item.qty || item.qty < 1) errors.push(`Item #${i + 1}: Quantity must be at least 1`);
        });
    }

    return errors;
}

