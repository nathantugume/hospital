        row.remove();
        updateSummary();
    });

    row.querySelectorAll('input, select').forEach(el => {
        el.addEventListener('input', updateSummary);
        el.addEventListener('change', updateSummary);
    });

    // Add data attribute for easy selection
    row.classList.add('item-row');
    return row;
}

