// Render Month View
function renderMonthView() {
    const container = document.getElementById('monthView');
    const monthDays = getMonthDays(currentDate);
    
    const headerHtml = `<div class="grid grid-cols-7 gap-2 mb-2"><div class="text-center p-1 md:p-2 font-medium text-xs md:text-sm">Sun</div><div class="text-center p-1 md:p-2 font-medium text-xs md:text-sm">Mon</div><div class="text-center p-1 md:p-2 font-medium text-xs md:text-sm">Tue</div><div class="text-center p-1 md:p-2 font-medium text-xs md:text-sm">Wed</div><div class="text-center p-1 md:p-2 font-medium text-xs md:text-sm">Thu</div><div class="text-center p-1 md:p-2 font-medium text-xs md:text-sm">Fri</div><div class="text-center p-1 md:p-2 font-medium text-xs md:text-sm">Sat</div></div>`;
    
    const weeks = [];
    for (let i = 0; i < monthDays.length; i += 7) weeks.push(monthDays.slice(i, i + 7));
    
    const monthHtml = weeks.map(week => `<div class="grid grid-cols-7 gap-2 mb-2">${week.map(date => {
        if (!date) return `<div class="border rounded-md p-0.5 md:p-1 h-24 bg-gray-50/20"></div>`;
        const dateKey = formatDateKey(date);
        const dayAppointments = getAppointmentsForDate(dateKey);
        const isToday = dateKey === formatDateKey(new Date());
        const isCurrentMonth = date.getMonth() === currentDate.getMonth();
        return `<div class="border rounded-md p-0.5 md:p-2 h-24 overflow-y-auto ${isToday ? 'border-indigo-400 bg-indigo-50/10' : ''} ${!isCurrentMonth ? 'bg-gray-50/30 text-gray-400' : ''}"><div class="text-right text-xs md:text-sm font-medium mb-1 ${isToday ? 'text-indigo-600 font-bold' : ''}">${date.getDate()}</div><div class="space-y-1">${dayAppointments.slice(0, 2).map(a => `<div class="p-0.5 md:p-1 rounded text-xs ${getStatusColorClass(a.status)} border truncate cursor-pointer hover:bg-opacity-20" onclick="showAppointmentDetails(${a.id})" title="${a.time} - ${a.endTime || a.time} - ${a.patient}">${a.time.substring(0,5)} - ${a.patient.split(' ')[0]}</div>`).join('')}${dayAppointments.length > 2 ? `<div class="text-xs text-gray-400 text-center">+${dayAppointments.length - 2} more</div>` : ''}</div></div>`;
    }).join('')}</div>`).join('');
    
    container.innerHTML = headerHtml + `<div class="space-y-2">${monthHtml}</div>`;
}

function renderCurrentView() {
    document.getElementById('currentDateDisplay').innerText = formatDate(currentDate);
    if (currentView === 'day') renderDayView();
    else if (currentView === 'week') renderWeekView();
    else renderMonthView();
}

// Navigation
function updateDate(delta) {
    if (currentView === 'day') currentDate.setDate(currentDate.getDate() + delta);
    else if (currentView === 'week') currentDate.setDate(currentDate.getDate() + (delta * 7));
    else { currentDate.setMonth(currentDate.getMonth() + delta); }
    renderCurrentView();
}

function goToToday() {
    currentDate = new Date();
    renderCurrentView();
}

// Tab switching
const viewTriggers = document.querySelectorAll('.view-trigger');
const viewPanels = { day: document.getElementById('dayView'), week: document.getElementById('weekView'), month: document.getElementById('monthView') };

function switchView(view) {
    currentView = view;
    Object.keys(viewPanels).forEach(v => viewPanels[v].classList.add('hidden'));
    viewPanels[view].classList.remove('hidden');
    viewTriggers.forEach(trigger => {
        const isActive = trigger.getAttribute('data-view') === view;
        trigger.setAttribute('data-state', isActive ? 'active' : 'inactive');
        if (isActive) trigger.classList.add('bg-white', 'text-gray-900', 'shadow-sm');
        else trigger.classList.remove('bg-white', 'text-gray-900', 'shadow-sm');
    });
    renderCurrentView();
}

viewTriggers.forEach(trigger => trigger.addEventListener('click', () => switchView(trigger.getAttribute('data-view'))));

