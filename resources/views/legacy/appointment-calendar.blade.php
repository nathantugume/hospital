        appointments.push(newApt);
        saveAppointmentsToStorage(appointments);
        showToast(`New appointment for ${newApt.patient} added!`);
    }
    sessionStorage.removeItem('newlyAddedAppointment');
}

// Check for updated appointment from sessionStorage
const updatedAppointment = sessionStorage.getItem('updatedAppointment');
if (updatedAppointment) {
    const updatedApt = JSON.parse(updatedAppointment);
    const index = appointments.findIndex(a => a.id === updatedApt.id);
    if (index !== -1) {
        appointments[index] = updatedApt;
        saveAppointmentsToStorage(appointments);
        showToast(`Appointment for ${updatedApt.patient} updated!`);
    }
    sessionStorage.removeItem('updatedAppointment');
}

// Check for deleted appointment from sessionStorage
const deletedAppointmentId = sessionStorage.getItem('deletedAppointmentId');
if (deletedAppointmentId) {
    const deletedApt = appointments.find(a => a.id == deletedAppointmentId);
    appointments = appointments.filter(a => a.id != deletedAppointmentId);
    saveAppointmentsToStorage(appointments);
    if (deletedApt) showToast(`Appointment for ${deletedApt.patient} cancelled.`);
    sessionStorage.removeItem('deletedAppointmentId');
}

