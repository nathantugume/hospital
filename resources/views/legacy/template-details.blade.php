    // Delete Modal Logic (covers sidebar)
    const deleteModal = document.getElementById('deleteModal');
    const deleteModalBackdrop = document.getElementById('deleteModalBackdrop');
    
    function openDeleteModal() {
        const modalTitle = document.getElementById('modalTitle');
        const modalDescription = document.getElementById('modalDescription');
        modalTitle.innerText = 'Are you sure you want to Delete this template?';
        modalDescription.innerText = `This will permanently delete the "${templateData.name}" template. This action cannot be undone.`;
        deleteModal.classList.remove('hidden');
        deleteModalBackdrop.classList.remove('hidden');
        document.body.style.overflow = 'hidden';
        document.body.style.position = 'fixed';
        document.body.style.width = '100%';
    }
    
    function closeDeleteModal() {
        deleteModal.classList.add('hidden');
        deleteModalBackdrop.classList.add('hidden');
        document.body.style.overflow = '';
        document.body.style.position = '';
        document.body.style.width = '';
    }
    
    // Delete button click
    document.getElementById('deleteBtn')?.addEventListener('click', openDeleteModal);
    
    // Modal cancel button
    document.getElementById('modalCancelBtn')?.addEventListener('click', closeDeleteModal);
    
    // Modal backdrop click
    deleteModalBackdrop?.addEventListener('click', closeDeleteModal);
    
    // Confirm delete button
    document.getElementById('modalConfirmDeleteBtn')?.addEventListener('click', () => {
        console.log(`Deleting template: ${templateData.name}`);
        // Show toast or notification instead of alert
        const notification = document.createElement('div');
        notification.className = 'fixed bottom-4 right-4 bg-green-500 text-white px-4 py-2 rounded-md shadow-lg z-[10001]';
        notification.innerText = `✅ Template "${templateData.name}" deleted successfully!`;
        document.body.appendChild(notification);
