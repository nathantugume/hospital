    function createRadixSelect(options, defaultValue, placeholder) {
        const wrapper = document.createElement('div');
        wrapper.className = 'radix-select-wrap';
        wrapper.style.cssText = 'position:relative;width:100%;';
        
        const selectedOption = options.find(o => o.value === defaultValue) || options[0];
        const isDark = document.body.classList.contains('dark');
        
        wrapper.innerHTML = `
            <button type="button" class="radix-select-trigger" style="display:flex;align-items:center;justify-content:space-between;width:100%;height:40px;border-radius:0.375rem;border:1px solid ${isDark ? '#404040' : '#d1d5db'};background-color:${isDark ? '#262626' : 'white'};padding:0 0.75rem;font-size:0.875rem;cursor:pointer;text-align:left;color:${isDark ? '#e5e5e5' : '#374151'};">
                <span class="flex-1">${selectedOption ? selectedOption.label : placeholder}</span>
                <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><polyline points="6 9 12 15 18 9"/></svg>
            </button>
            <div class="radix-select-content" style="display:none;position:absolute;top:calc(100% + 4px);left:0;width:100%;max-height:240px;overflow-y:auto;background:${isDark ? '#2a2a2a' : 'white'};border:1px solid ${isDark ? '#404040' : '#e5e7eb'};border-radius:0.5rem;box-shadow:0 10px 25px rgba(0,0,0,0.12);z-index:10001;animation:radixSlideDown 0.15s ease-out;">
