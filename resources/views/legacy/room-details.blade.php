                    <div class="radix-select-item" data-value="${opt.value}" style="padding:0.5rem 0.75rem;font-size:0.875rem;cursor:pointer;display:flex;align-items:center;justify-content:space-between;color:${isDark ? '#e5e5e5' : '#374151'};">
                        ${opt.label}
                        <span class="radix-select-check" style="display:${opt.value === (selectedOption?.value) ? 'block' : 'none'};width:16px;height:16px;color:#6366f1;">
                            <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><polyline points="20 6 9 17 4 12"/></svg>
                        </span>
                    </div>
                `).join('')}
            </div>
        `;
        
        const trigger = wrapper.querySelector('.radix-select-trigger');
        const content = wrapper.querySelector('.radix-select-content');
        const items = wrapper.querySelectorAll('.radix-select-item');
        
        let currentValue = selectedOption?.value || '';
        
        trigger.addEventListener('click', (e) => {
            e.stopPropagation();
            document.querySelectorAll('.radix-select-content').forEach(c => {
                if (c !== content) c.style.display = 'none';
            });
            content.style.display = content.style.display === 'none' ? 'block' : 'none';
        });
        
        items.forEach(item => {
            item.addEventListener('click', (e) => {
                e.stopPropagation();
                const value = item.dataset.value;
                const label = item.textContent.trim();
                
                trigger.querySelector('span').textContent = label;
                currentValue = value;
                
                items.forEach(i => {
                    const check = i.querySelector('.radix-select-check');
                    if (check) check.style.display = 'none';
                });
                const check = item.querySelector('.radix-select-check');
                if (check) check.style.display = 'block';
                
                content.style.display = 'none';
            });
            
            // Hover effect
            item.addEventListener('mouseenter', () => {
                item.style.backgroundColor = isDark ? '#3f3f46' : '#f3f4f6';
            });
            item.addEventListener('mouseleave', () => {
                item.style.backgroundColor = '';
            });
        });
        
        document.addEventListener('click', (e) => {
            if (!wrapper.contains(e.target)) {
                content.style.display = 'none';
            }
        });
        
        wrapper.getValue = () => currentValue;
        wrapper.setValue = (value) => {
            const option = options.find(o => o.value === value);
            if (option) {
                trigger.querySelector('span').textContent = option.label;
                currentValue = value;
                items.forEach(i => {
                    const check = i.querySelector('.radix-select-check');
                    if (check) check.style.display = i.dataset.value === value ? 'block' : 'none';
                });
            }
        };
        
        return wrapper;
    }

